create_shell_template() {
  local repo_name="$1"
  cat > "$repo_name/build.sh" << 'SHELL'
#!/bin/bash
# C25 Build Script - {REPO_NAME}
# Auto-generated by c25-repo-scaffolder

set -euo pipefail

REPO_NAME="{REPO_NAME}"
BUILD_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
LOG_DIR="$BUILD_DIR/.build-logs"
mkdir -p "$LOG_DIR"

echo "🔨 Building $REPO_NAME..."

# Install dependencies
if [ -f "requirements.txt" ]; then
  echo "  Installing Python deps..."
  pip install -q -r requirements.txt
fi

if [ -f "package.json" ]; then
  echo "  Installing Node deps..."
  npm install --silent
fi

# Build
echo "  Building..."

if [ -f "src/main/java/*.java" ]; then
  echo "  Compiling Java..."
  javac src/main/java/*.java
fi

if [ -f "package.json" ]; then
  echo "  Building Node project..."
  npm run build 2>/dev/null || true
fi

echo "✅ Build complete: $REPO_NAME"
SHELL
  chmod +x "$repo_name/build.sh"
  echo "✓ Created build.sh"
}


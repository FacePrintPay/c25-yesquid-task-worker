scaffold_repo() {
  local repo_name="$1"
  local repo_path="$WORK_DIR/$repo_name"
  
  echo "" | tee -a "$LOG_FILE"
  echo -e "${C}Scaffolding: $repo_name${NC}" | tee -a "$LOG_FILE"
  
  mkdir -p "$repo_path"
  cd "$repo_path"
  
  # Check which files exist
  local missing_files=()
  [ ! -f "main.py" ] && missing_files+=("python")
  [ ! -f "config.json" ] && missing_files+=("json")
  [ ! -f "src/main/java/C25Module.java" ] && missing_files+=("java")
  [ ! -f "README.md" ] && missing_files+=("markdown")
  [ ! -f "build.sh" ] && missing_files+=("shell")
  [ ! -f "index.html" ] && missing_files+=("html")
  
  if [ ${#missing_files[@]} -eq 0 ]; then
    echo -e "  ${G}✓ All files present${NC}" | tee -a "$LOG_FILE"
    return 0
  fi
  
  echo -e "  ${Y}Creating missing files:${NC}" | tee -a "$LOG_FILE"
  
  for file_type in "${missing_files[@]}"; do
    case "$file_type" in
      python) create_python_template "$repo_path" ;;
      java) create_java_template "$repo_path" ;;
      json) create_json_template "$repo_path" ;;
      markdown) create_markdown_template "$repo_path" ;;
      shell) create_shell_template "$repo_path" ;;
      html) create_index_html_template "$repo_path" ;;
    esac 2>&1 | tee -a "$LOG_FILE"
  done
  
  # Also create package.json and requirements.txt
  create_package_json_template "$repo_path"
  create_requirements_txt_template "$repo_path"
  
  echo -e "  ${G}✅ Scaffolded${NC}" | tee -a "$LOG_FILE"
}

# ─────────────────────────────────────────────────
# GET REPOS AND SCAFFOLD
# ─────────────────────────────────────────────────

if [ $# -gt 0 ]; then
  # Single repo mode
  scaffold_repo "$1"
else
  # All repos mode - list of priority repos
  PRIORITY_REPOS=(
    "VideoCourts"
    "SovereignGTP"
    "PaThosAi"
    "constellation25"
    "MyBuyo"
    "TotalRecall"
    "c25-yesquid-task-worker"
    "agentik"
    "aikre8tive"
    "AiKre8tive-Stargate"
  )
  
  for repo in "${PRIORITY_REPOS[@]}"; do
    scaffold_repo "$repo"
  done
fi

echo "" | tee -a "$LOG_FILE"
echo "════════════════════════════════════════════" | tee -a "$LOG_FILE"
echo -e "${G}✅ Scaffolding complete${NC}" | tee -a "$LOG_FILE"
echo "Log: $LOG_FILE" | tee -a "$LOG_FILE"

#!/bin/bash
# C25 Repo Scaffolder - Ensure ALL repos have required file types
# Usage: bash c25-repo-scaffolder.sh [optional_repo_name]

set -euo pipefail

# Colors
G='\033[0;32m'
Y='\033[1;33m'
R='\033[0;31m'
C='\033[0;36m'
NC='\033[0m'

# Config
OWNER="FacePrintPay"
WORK_DIR="$HOME/c25-scaffold"
LOG_FILE="$WORK_DIR/scaffold.log"
mkdir -p "$WORK_DIR"

